test('tactics replace a failed profile request with an actionable retry', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '战术', exact: true }).click()
  const failedProfile = '**/data/v4/tactics/team-788bd487bf857297.json*'
  await page.route(failedProfile, route => route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html>' }))
  await page.getByLabel('我方执行队伍').selectOption({ label: '深圳技术大学' })
  await expect(page.getByText('战术画像返回格式错误，请重启开发服务后重试')).toBeVisible()
  await expect(page.getByText('正在匹配双方战术画像…')).toHaveCount(0)
  await page.unroute(failedProfile)
  await page.getByRole('button', { name: '重新加载' }).last().click()
  await expect(page.locator('.counter-plan-card')).toHaveCount(3)
})

test('methodology is contextual and returns focus when closed', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByRole('button', { name: '数据口径' })
  await trigger.click()
  await expect(page.getByRole('dialog', { name: '数据口径 · 总览' })).toBeVisible()
  await expect(page.getByText('评分阅读')).toBeVisible()
  await expect(page.getByRole('button', { name: '关闭', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '关闭', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

