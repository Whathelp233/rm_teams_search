test('mobile filters open without horizontal page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const method = page.getByRole('button', { name: '数据口径' })
  const filter = page.getByRole('button', { name: '筛选', exact: true })
  await expect(method).toBeVisible()
  await expect(filter).toBeVisible()
  const [methodBox, filterBox] = await Promise.all([method.boundingBox(), filter.boundingBox()])
  expect(methodBox.x + methodBox.width).toBeLessThanOrEqual(filterBox.x)
  await filter.click()
  await expect(page.getByText('队伍检索', { exact: true })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  expect(overflow).toBeFalsy()
})
