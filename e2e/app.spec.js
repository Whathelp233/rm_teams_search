test('default overview is lightweight and opens Guangdong University of Technology', async ({ page }) => {
  const requested = []
  page.on('request', request => requested.push(request.url()))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '广东工业大学' })).toBeVisible()
  await expect(page.getByRole('button', { name: '总览' })).toHaveClass(/active/)
  expect(requested.some(url => url.includes('/heatmaps/'))).toBeFalsy()
  expect(requested.some(url => url.includes('/roles/hero/'))).toBeFalsy()
  expect(requested.some(url => url.includes('/repechage.json'))).toBeFalsy()
  expect(requested.some(url => url.includes('/v4/tactics/'))).toBeFalsy()
})

